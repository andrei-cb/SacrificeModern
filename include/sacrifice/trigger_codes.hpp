// Special entity selectors are stored in the trigger stream's little-endian character convention;
// they are not ordinary resource FourCC IDs such as CRE8:psnt. The label table also names 'yctt' (Carrying
// creature) and '1mct'..'8mct' (Multiplayer Wizard 1..8); neither the game nor the editor uses them.
enum EntityType : std::uint32_t {
    EntityCurrentWizard = 1952675683,
    EntitySingleplayerWizard = 1952675699, // Native: the object the player controls, else the local side's wizard.
    EntityTypeAltars = 1953784172,
    EntityTypeCorpses = 1953784688,
    EntityTypeCreatures = 1953784690,
    EntityTypeFlyingCreatures = 1953785452,
    EntityTypeMeleeCreatures = 1953787237, // The game does not test melee: every non-corpse creature counts.
    EntityTypeManafonts = 1953787238,
    EntityTypeManaliths = 1953787246,
    EntityTypeRangedCreatures = 1953788513, // The game does not test ranged: every non-corpse creature counts.
    EntityTypeControllableCreatures = 1953788780, // Wizards count too.
    EntityTypeWizardsAndCreatures = 1953789795,
    EntityTypeWizards = 1953789818,
};

