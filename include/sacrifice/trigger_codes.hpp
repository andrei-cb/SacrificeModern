// Serialized trigger vocabulary. Codes come from the original ScapeX editor's trigger table (scapex.exe
// 0x43aa38..0x43df48: display phrase, code, operand types). The editor has no identifiers: names are built
// from its phrases, with operand types telling apart codes that share a phrase (53/54, 55/152, 153/234).
// Entity selector names follow the game's TEXT labels in data/local/lang_english.wad.
// Codes 263..269 appear in the editor but not in the game's instruction tables.
// "Unused" marks codes that no installed map uses (docs/trigger_inventory.md).
// Unscoped enumerators deliberately convert to the archive's u32 words; each name carries its domain.
// Each enum lists its enumerators in ascending value order (shared values keep their domain order).
